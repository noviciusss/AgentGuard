"""Plugin management and environment diagnostics commands."""

from __future__ import annotations

import re
from pathlib import Path
from textwrap import dedent
from typing import Annotated

import typer

from agentguard.config import ConfigError, load_config
from agentguard.plugins.manager import PluginManager

plugins_app = typer.Typer(help="Inspect and scaffold AgentGuard plugins.")


@plugins_app.command("list")
def list_command() -> None:
    """List built-in and installed plugins."""
    manager = PluginManager.default()
    for plugin in manager.plugins():
        suffix = " [load error]" if _has_error(manager, plugin.name) else ""
        typer.echo(f"{plugin.name}  {plugin.version}  {plugin.module}{suffix}")
    for error in manager.load_errors():
        typer.echo(f"warning: {error}", err=True)


@plugins_app.command("info")
def info_command(name: str) -> None:
    """Show a plugin's metadata and contributions."""
    manager = PluginManager.default()
    try:
        plugin = manager.info(name)
    except KeyError as error:
        typer.echo(f"unknown plugin: {name}", err=True)
        raise typer.Exit(code=2) from error
    typer.echo(f"name: {plugin.name}")
    typer.echo(f"version: {plugin.version}")
    typer.echo(f"module: {plugin.module}")
    for hook, values in sorted(manager.contributions(name).items()):
        rendered = ", ".join(values) if values else "implemented"
        typer.echo(f"{hook}: {rendered}")


@plugins_app.command("new")
def new_command(
    name: str,
    destination: Annotated[
        Path,
        typer.Option("--destination", help="Directory in which to create the plugin."),
    ] = Path("."),
) -> None:
    """Create a minimal external plugin package."""
    package_name = _package_name(name)
    if package_name is None:
        typer.echo(
            "plugin name must contain only letters, numbers, hyphens, or underscores",
            err=True,
        )
        raise typer.Exit(code=2)
    root = destination.resolve() / package_name
    if root.exists():
        typer.echo(f"destination already exists: {root}", err=True)
        raise typer.Exit(code=2)
    module_name = package_name.replace("-", "_")
    package_dir = root / "src" / module_name
    tests_dir = root / "tests"
    package_dir.mkdir(parents=True)
    tests_dir.mkdir()
    (root / "README.md").write_text(
        f"# {package_name}\n\nGenerated AgentGuard plugin.\n", encoding="utf-8"
    )
    (root / "pyproject.toml").write_text(
        _pyproject_template(package_name, module_name), encoding="utf-8"
    )
    (package_dir / "__init__.py").write_text(
        _plugin_template(module_name), encoding="utf-8"
    )
    (tests_dir / "test_plugin.py").write_text(
        "def test_plugin_package_imports() -> None:\n"
        f"    import {module_name}\n"
        f"    assert {module_name}.Plugin.name\n",
        encoding="utf-8",
    )
    typer.echo(f"created {root}")


@plugins_app.command("doctor")
def doctor_command() -> None:
    """Check configuration and plugin discovery health."""
    manager = PluginManager.default()
    problems = list(manager.load_errors())
    try:
        load_config(Path.cwd())
    except ConfigError as error:
        problems.append(str(error))
    if problems:
        for problem in problems:
            typer.echo(f"error: {problem}", err=True)
        raise typer.Exit(code=1)
    typer.echo(f"ok: {len(manager.plugins())} plugins discovered")


def _package_name(name: str) -> str | None:
    normalized = name.strip()
    if not normalized or re.fullmatch(r"[A-Za-z0-9_-]+", normalized) is None:
        return None
    return normalized


def _has_error(manager: PluginManager, name: str) -> bool:
    return any(error.startswith(f"{name}:") for error in manager.load_errors())


def _pyproject_template(package_name: str, module_name: str) -> str:
    return dedent(
        f"""
        [build-system]
        requires = ["hatchling>=1.27,<2"]
        build-backend = "hatchling.build"

        [project]
        name = "{package_name}"
        version = "0.1.0"
        requires-python = ">=3.10"
        dependencies = ["agentguard>=0.1"]

        [project.entry-points.agentguard]
        {module_name} = "{module_name}:Plugin"

        [tool.hatch.build.targets.wheel]
        packages = ["src/{module_name}"]
        """
    ).lstrip()


def _plugin_template(module_name: str) -> str:
    return dedent(
        f"""
        from agentguard.plugins import hookimpl
        from agentguard.rules.base import Rule, RuleContext
        from agentguard.findings import Finding


        class ExampleRule(Rule):
            rule_id = "AG900"
            name = "{module_name}-example"
            description = "Example rule generated by AgentGuard."

            def check(self, context: RuleContext) -> list[Finding]:
                return []


        class Plugin:
            name = "{module_name}"

            @hookimpl
            def register_rules(self) -> list[type[Rule]]:
                return [ExampleRule]
        """
    ).lstrip()
